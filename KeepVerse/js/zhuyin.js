/**
 * 將經文轉換為「第一個注音符號（聲母或零聲母首音）」提示字串，保留標點符號。
 * @param {string} text
 * @returns {string}
 */
export function toZhuyinInitials(text) {
  const chars = Array.from(String(text || ''));
  const out = [];
  let i = 0;

  while (i < chars.length) {
    let matched = false;
    for (let len = 4; len >= 2; len -= 1) {
      if (i + len > chars.length) continue;
      const phrase = chars.slice(i, i + len).join('');
      const reading = POLYPHONE_PHRASES.get(phrase);
      if (reading) {
        out.push(reading);
        i += len;
        matched = true;
        break;
      }
    }
    if (!matched) {
      const ch = chars[i];
      out.push(CHAR_TO_ZHUYIN.get(ch) ?? ch);
      i += 1;
    }
  }

  return out.join('');
}
